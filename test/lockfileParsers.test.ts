import { describe, it, expect } from 'vitest';
import { parseYarnLockfile, parsePnpmLockfile } from '../src/analyzer/lockfileParsers';

describe('parseYarnLockfile', () => {
  const sample = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


axios@^1.0.0, axios@^1.6.0:
  version "1.6.0"
  resolved "https://registry.yarnpkg.com/axios/-/axios-1.6.0.tgz#abc123"
  integrity sha512-fakefakefakefakefakefakefakefakefakefakefakefakefakefakefakefakefakefak==
  dependencies:
    follow-redirects "^1.15.0"

"@scope/pkg@^2.0.0":
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/@scope/pkg/-/pkg-2.0.0.tgz#def456"
  integrity sha512-anotherfakehashanotherfakehashanotherfakehashanotherfakehash==

no-integrity-pkg@^1.0.0:
  version "1.0.0"
  resolved "file:../local-patch"
`;

  it('extracts name, version, resolved, and integrity for a plain package', () => {
    const entries    = parseYarnLockfile(sample);
    const axios       = entries.find(e => e.name === 'axios');
    expect(axios).toBeDefined();
    expect(axios?.version).toBe('1.6.0');
    expect(axios?.resolved).toBe('https://registry.yarnpkg.com/axios/-/axios-1.6.0.tgz#abc123');
    expect(axios?.integrity).toContain('sha512-');
  });

  it('extracts a scoped package name correctly', () => {
    const entries = parseYarnLockfile(sample);
    const scoped   = entries.find(e => e.name === '@scope/pkg');
    expect(scoped).toBeDefined();
    expect(scoped?.version).toBe('2.0.0');
  });

  it('leaves integrity undefined when the entry has none', () => {
    const entries = parseYarnLockfile(sample);
    const noInteg   = entries.find(e => e.name === 'no-integrity-pkg');
    expect(noInteg).toBeDefined();
    expect(noInteg?.integrity).toBeUndefined();
    expect(noInteg?.resolved).toBe('file:../local-patch');
  });

  it('rejects a Yarn Berry (v2+) lockfile instead of silently misreading it', () => {
    const berry = `__metadata:\n  version: 6\n\n"axios@npm:1.6.0":\n  version: 1.6.0\n`;
    expect(() => parseYarnLockfile(berry)).toThrow(/Yarn Berry/);
  });
});

describe('parsePnpmLockfile', () => {
  const sample = `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true

importers:
  .:
    dependencies:
      axios:
        specifier: ^1.6.0
        version: 1.6.0

packages:

  axios@1.6.0:
    resolution: {integrity: sha512-fakefakefakefakefakefakefakefakefakefakefakefakefakefakefakefakefakefak==}
    engines: {node: '>=0.1.90'}

  '@scope/pkg@2.0.0':
    resolution: {integrity: sha512-anotherfakehashanotherfakehashanotherfakehashanotherfakehash==}

  local-patch@1.0.0:
    resolution: {tarball: file:../local-patch.tgz}

snapshots:

  axios@1.6.0: {}
`;

  it('extracts name, version, and integrity for a plain package', () => {
    const entries    = parsePnpmLockfile(sample);
    const axios       = entries.find(e => e.name === 'axios');
    expect(axios).toBeDefined();
    expect(axios?.version).toBe('1.6.0');
    expect(axios?.integrity).toContain('sha512-');
  });

  it('extracts a quoted scoped package entry with the quotes stripped', () => {
    const entries = parsePnpmLockfile(sample);
    const scoped   = entries.find(e => e.name === '@scope/pkg');
    expect(scoped).toBeDefined();
    expect(scoped?.version).toBe('2.0.0');
    expect(scoped?.integrity).toContain('sha512-');
  });

  it('captures a tarball resolution (non-registry source) with no integrity', () => {
    const entries = parsePnpmLockfile(sample);
    const local     = entries.find(e => e.name === 'local-patch');
    expect(local).toBeDefined();
    expect(local?.integrity).toBeUndefined();
    expect(local?.resolved).toBe('file:../local-patch.tgz');
  });

  it('stops at the snapshots: section and does not misread it as packages', () => {
    const entries = parsePnpmLockfile(sample);
    expect(entries.filter(e => e.name.includes('axios'))).toHaveLength(1);
  });

  it('throws when there is no packages: section at all', () => {
    expect(() => parsePnpmLockfile('lockfileVersion: "9.0"\nimporters:\n  .: {}\n')).toThrow(/packages:/);
  });
});
